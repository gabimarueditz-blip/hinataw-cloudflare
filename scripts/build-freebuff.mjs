// Builds the Freebuff Sites deployment bundle:
//   1. Generates workers/shims/preloaded.js from selected data/*.json files
//      (hianime-cache = catalog seed; users/feedback = local data migration;
//      notices intentionally EXCLUDED so the unwanted default Welcome notice
//      is not resurrected on the new host).
//   2. Bundles workers/entry.js → freebuff/dist/worker.js (single ESM module,
//      minified, Node builtins aliased to Workers shims).
//   3. Writes freebuff/dist/manifest.json for sites_deploy.
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// esbuild must resolve from the project itself so this script also works on
// CI (Cloudflare Workers Builds runs on Linux, where the old D:/hinataw-tools
// path of the original dev machine cannot exist).
const require = createRequire(import.meta.url);
let esbuild;
try {
  esbuild = require("esbuild");
} catch {
  try {
    // Legacy fallback for the original Windows dev machine.
    esbuild = createRequire("D:/hinataw-tools/package.json")("esbuild");
  } catch {
    console.error("[build] esbuild not found — run `npm install` first (it is a devDependency)");
    process.exit(1);
  }
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// --- 1. preloaded.js -------------------------------------------------------
const PRELOAD_KEYS = ["hianime-cache", "users", "feedback"]; // NOT notices
const preloaded = {};
for (const key of PRELOAD_KEYS) {
  const p = path.join(root, "data", key + ".json");
  if (fs.existsSync(p)) {
    preloaded["data/" + key + ".json"] = fs.readFileSync(p, "utf8");
    console.log(`[build] preload data/${key}.json (${preloaded["data/" + key + ".json"].length} bytes)`);
  } else {
    console.log(`[build] data/${key}.json missing — skipping`);
  }
}
const preloadedPath = path.join(root, "workers", "shims", "preloaded.js");
fs.writeFileSync(
  preloadedPath,
  "// AUTO-GENERATED by scripts/build-freebuff.mjs — do not edit.\n" +
    "export const PRELOADED = " + JSON.stringify(preloaded) + ";\n",
  "utf8"
);

// --- 2. bundle -------------------------------------------------------------
const outDir = path.join(root, "freebuff", "dist");
fs.mkdirSync(outDir, { recursive: true });

const shim = (name) => path.join(root, "workers", "shims", name);

const result = await esbuild.build({
  entryPoints: [path.join(root, "workers", "entry.js")],
  outfile: path.join(outDir, "worker.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  minify: true,
  sourcemap: false,
  charset: "utf8",
  logLevel: "warning",
  legalComments: "none",
  inject: [shim("buffer-inject.js")],
  alias: {
    fs: shim("fs.js"),
    "node:fs": shim("fs.js"),
    "node:fs/promises": shim("fs-promises.js"),
    path: shim("path.js"),
    "node:path": shim("path.js"),
    url: shim("url.js"),
    "node:url": shim("url.js"),
    crypto: shim("crypto.js"),
    "node:crypto": shim("crypto.js"),
    vm: shim("vm.js"),
    "node:vm": shim("vm.js"),
    "wreq-js": shim("wreq-stub.js"),
  },
  banner: {
    js: "globalThis.process = globalThis.process || { env: {}, versions: {}, platform: \"workers\", cwd: () => \"/\" };",
  },
  loader: { ".json": "json" },
  define: {},
});

for (const w of result.warnings) console.warn("[build] warning:", w.text);

// --- 3. manifest -----------------------------------------------------------
const manifest = {
  entrypoint: "index.js",
  compatibilityDate: "2026-10-01",
  modules: [
    { name: "index.js", type: "esm", path: "./worker.js" },
  ],
};
fs.writeFileSync(path.join(outDir, "manifest.json"), JSON.stringify(manifest, null, 2), "utf8");

const size = fs.statSync(path.join(outDir, "worker.js")).size;
console.log(`[build] worker.js: ${(size / 1024 / 1024).toFixed(2)} MiB`);
console.log(`[build] manifest.json written (compatibilityDate ${manifest.compatibilityDate})`);
if (size > 9.5 * 1024 * 1024) {
  console.error("[build] FATAL: worker bundle exceeds 10 MiB upload limit");
  process.exit(1);
}
